const LEGATO = { p1: 0.97, p2: 0.96, tri: 0.92 };
const BASE_VEL = { p1: 78, p2: 60, tri: 84 };

function buildSong(r) {
	const spb = 60 / r.bpm;
	const notes = [];
	r.form.forEach((sec, s) => {
		const startBar = s * 8;
		const scale = (r.velScale && r.velScale[sec]) || 1;
		const leadSec = [];
		expandChannel(leadSec, 'p1', r.lead[r.leadMap[sec]], startBar, spb, BASE_VEL.p1 * scale,
			{ duty: r.duty, vib: r.vib, legato: LEGATO.p1 });
		notes.push(...leadSec);
		const hBlock = r.harmMap[sec];
		if (hBlock === 'PAR') {
			notes.push(...parallelThirds(leadSec, SCALES[r.scale], 16));
		} else {
			expandChannel(notes, 'p2', r.harm[hBlock], startBar, spb, BASE_VEL.p2 * scale,
				{ duty: 0.5, vib: 0, legato: LEGATO.p2 });
		}
		expandChannel(notes, 'tri', r.bass[r.bassMap[sec]], startBar, spb, BASE_VEL.tri * scale,
			{ duty: 0, vib: 0, legato: LEGATO.tri });
		expandDrums(notes, r.drums[r.drumMap[sec]], startBar, spb, Math.min(1, scale));
	});
	notes.sort((a, b) => a.t - b.t || (a.midi || 0) - (b.midi || 0));
	const duration = 32 * 4 * spb;
	for (const n of notes) {
		if (n.c !== 'drm' && (n.midi < 30 || n.midi > 96)) throw new Error('音域越界 ' + r.id + ' midi=' + n.midi);
		if (n.t + 0.001 > duration) throw new Error('音符超出结尾 ' + r.id);
	}
	return {
		id: r.id, title: r.title, use: r.use, key: r.key, bpm: r.bpm, bar_count: 32,
		echo_delay: 0.75 * spb, echo_mix: r.echoMix, duration, notes,
	};
}

const scores = SONGS.map(buildSong);
for (const s of scores) {
	console.log('COMPOSED ' + s.id + ' 《' + s.title + '》 ' + s.key + ' ' + s.bpm + ' BPM · '
		+ s.notes.length + ' notes · ' + s.duration.toFixed(2) + ' s');
}
fs.writeFileSync(path.join(__dirname, 'chip_scores.json'), JSON.stringify(scores, null, 2) + '\n');
