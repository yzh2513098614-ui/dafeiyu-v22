function pitch(name) {
	if (name === 'R') return -1;
	const m = name.match(/^([A-G])(#|b)?([2-6])$/);
	if (!m) throw new Error('Bad note ' + name);
	return (Number(m[3]) + 1) * 12 + { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 }[m[1]]
		+ (m[2] === '#' ? 1 : m[2] === 'b' ? -1 : 0);
}

function phrase(s) {
	const rows = s.split(' ').filter(t => t).map(t => {
		const [nv, d] = t.split(':');
		const mm = nv.match(/^(.+?)(?:@(\d+))?$/);
		return { p: pitch(mm[1]), d: Number(d), v: mm[2] ? Number(mm[2]) : null };
	});
	const sum = rows.reduce((a, r) => a + r.d, 0);
	if (Math.abs(sum - 4) > 1e-6) throw new Error('小节不满 4 拍 [' + sum + ']: ' + s);
	return rows;
}

function expandChannel(notes, chan, blockBars, startBar, spb, vel, opt) {
	blockBars.forEach((line, i) => {
		const bar = startBar + i;
		let beat = 0;
		for (const r of phrase(line)) {
			if (r.p >= 0) {
				notes.push({
					c: chan, midi: r.p,
					t: bar * 4 * spb + beat * spb,
					d: r.d * spb * opt.legato,
					v: r.v != null ? r.v : Math.round(vel),
					duty: opt.duty || 0,
					vib: (chan === 'p1' && r.d * spb >= 0.28) ? opt.vib : 0,
				});
			}
			beat += r.d;
		}
	});
}

function expandDrums(notes, blockBars, startBar, spb, scale) {
	const DEF = { K: 88, S: 74, H: 50, O: 56 };
	blockBars.forEach((line, i) => {
		const bar = startBar + i;
		for (const tok of line.split(' ').filter(t => t)) {
			const [kv, at] = tok.split(':');
			const mm = kv.match(/^([KSHO])(?:@(\d+))?$/);
			if (!mm) throw new Error('Bad drum ' + tok);
			const beat = Number(at);
			if (!(beat >= 0 && beat < 4)) throw new Error('鼓点越界 ' + tok);
			notes.push({ c: 'drm', kind: mm[1], t: bar * 4 * spb + beat * spb, d: 0.1,
				v: Math.round((mm[2] ? Number(mm[2]) : DEF[mm[1]]) * scale) });
		}
	});
}

// 平行三度：主旋律下方两个音阶级。chromatic 音取最近下方级再降两级。
function parallelThirds(leadNotes, scalePCs, velDrop) {
	const table = [];
	for (let oct = 2; oct <= 6; oct++) for (const pc of scalePCs) table.push((oct + 1) * 12 + pc);
	table.sort((a, b) => a - b);
	return leadNotes.map(n => {
		let i = table.findIndex(x => x > n.midi);
		if (i < 0) i = table.length;
		return { c: 'p2', midi: table[Math.max(0, i - 3)], t: n.t, d: n.d * 0.96,
			v: Math.max(30, n.v - velDrop), duty: 0.5, vib: 0 };
	});
}

